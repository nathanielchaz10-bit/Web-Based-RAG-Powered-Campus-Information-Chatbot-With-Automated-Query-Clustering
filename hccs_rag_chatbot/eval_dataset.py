def _expand(frames, fillers, key):
    seen, out = set(), []
    for filler in fillers:
        for frame in frames:
            q = frame.format(**{key: filler})
            if q not in seen:
                seen.add(q)
                out.append(q)
    return out


def build_dataset():
    """Return a list of (query_text, true_topic), shuffled deterministically."""
    rng = random.Random(SEED)
    data = []

    for topic, intents in TOPICS.items():
        pool = _expand(FRAMES, intents, "x")
        rng.shuffle(pool)
        for q in pool[:PER_TOPIC]:
            data.append((q, topic))

    directory = _expand(DIRECTORY_FRAMES, DIRECTORY_PLACES, "p")
    rng.shuffle(directory)
    for q in directory[:PER_TOPIC]:
        data.append((q, "Campus Directory"))

    for q in NOISE:
        data.append((q, "_noise"))

    rng.shuffle(data)
    return data


